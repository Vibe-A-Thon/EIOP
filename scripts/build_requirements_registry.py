"""Import the CP audit without promoting file references into completed features.

Existing registry IDs and metadata are retained. Historical status/receipt claims
move to legacy_claims; current status is governed by the explicit implementation
record. Test maps are generated by pytest --requirements-map, never text search.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from eoip.jobs import write_json
from eoip.verification.cp_registry import (
    load_audit,
    load_registry,
    load_routing,
    migrate_registry,
    validate_registry,
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, help="Defaults to the existing registry; imports preserve its records")
    parser.add_argument("--check", action="store_true", help="Validate without changing files")
    parser.add_argument("--report", type=Path, help="Optional structured validation report")
    args = parser.parse_args()
    root = args.project_root.resolve()
    target = args.output or root / "requirements-registry.json"
    try:
        audit = load_audit(root)
        routing = load_routing(root, audit)
        existing_path = target if target.exists() else root / "requirements-registry.json"
        existing = load_registry(existing_path) if existing_path.exists() else []
        records = existing if args.check else migrate_registry(existing, audit, routing)
        report = validate_registry(root, records, audit)
        if not args.check and report["valid"]:
            write_json(target, records, indent=2)
    except (ValueError, OSError, KeyError) as exc:
        report = {"valid": False, "errors": [str(exc)]}
    if args.report:
        write_json(args.report, report)
    print(json.dumps(report, indent=2))
    raise SystemExit(0 if report["valid"] else 1)


if __name__ == "__main__":
    main()
